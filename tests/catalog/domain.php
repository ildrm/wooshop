<?php
declare(strict_types=1);
require dirname(__DIR__, 2) . '/packages/plugin/wooshop-commerce/autoload.php';

use WooShop\Commerce\Catalog\Input;
use WooShop\Commerce\Catalog\Search;
use WooShop\Commerce\Catalog\Units;
use WooShop\Commerce\Customer\CustomerService;
use WooShop\Commerce\Merchandising\Merchandising;
use WooShop\Commerce\Merchandising\PriceHistory;
use WooShop\Commerce\Merchandising\Loyalty;
use WooShop\Commerce\Merchandising\LoyaltyPolicy;
use WooShop\Commerce\Support\DomainError;

$count = 0;
$equal = static function ($actual, $expected, string $case) use (&$count): void { $count++; if ($actual !== $expected) { throw new RuntimeException($case . ': expected ' . var_export($expected, true) . ', received ' . var_export($actual, true)); } };
$reject = static function (callable $call, string $code) use ($equal): void { try { $call(); } catch (DomainError $error) { $equal($error->errorCode, $code, 'rejection'); return; } throw new RuntimeException('Expected rejection ' . $code); };

$equal(Units::convert('1000', 'g', 'kg'), '1', 'TEST-U041 mass conversion');
$equal(Units::convert('0.98', 'kg', 'g'), '980', 'TEST-U031 normalized pack weight');
$equal(Units::convert('1', 'lb', 'g'), '453.59237', 'exact approved lb factor');
$equal(Units::convert('0', 'g', 'kg'), '0', 'zero remains a real value');
$equal(Units::convert('-5.25', 'C', 'C'), '-5.25', 'signed temperature');
$equal(Units::format(Units::decimal('0.000001')), '0.000001', 'six digit precision');
$reject(static fn () => Units::convert('1000', 'mm', 'kg'), 'incompatible_unit');
$reject(static fn () => Units::convert('1', 'g', 'L'), 'incompatible_unit');
$reject(static fn () => Units::decimal('NaN'), 'invalid_decimal');
$reject(static fn () => Units::decimal('0.0000001'), 'invalid_decimal');
$reject(static fn () => Units::decimal('1e3'), 'invalid_decimal');
$reject(static fn () => Units::convert('999999', 'lb', 'g'), 'measurement_overflow');
$reject(static fn () => Input::keys(['product_id' => '12', 'owner' => 'user:2'], ['product_id']), 'invalid_fields');
$reject(static fn () => Input::bool('true'), 'invalid_boolean');
$reject(static fn () => Input::id(12), 'invalid_id');
$reject(static fn () => Input::id('0'), 'invalid_id');
$reject(static fn () => Input::id('1 OR 1=1'), 'invalid_id');
$reject(static fn () => Input::text('<script>alert(1)</script>', 1, 2000), 'invalid_text');
$equal(Input::id('12'), '12', 'native ID strings');
$equal(Input::uuid(Input::stableId('wishlist:guest:A')), Input::stableId('wishlist:guest:A'), 'stable aggregate UUID');
$equal(Input::stableId('wishlist:guest:A') !== Input::stableId('wishlist:guest:B'), true, 'guest aggregate separation');
$equal(Search::normalize('كیف ۲۲۰'), Search::normalize('کیف 220'), 'TEST-U042 Persian variants');
$equal(Search::normalize('SH-220-A'), 'sh-220-a', 'model punctuation preserved');
$equal(CustomerService::selectionKey(['product_id' => '1', 'variation_id' => '2']), '1:2::', 'variation identity retained');
$equal(CustomerService::selectionKey(['product_id' => '1', 'variation_id' => '2']) !== CustomerService::selectionKey(['product_id' => '1', 'variation_id' => '3']), true, 'variants do not collapse');
$equal(PriceHistory::minor('12.34', 2), '1234', 'TEST-U057 exact currency conversion');
$equal(PriceHistory::minor('0', 0), '0', 'zero minor price');
$reject(static fn () => PriceHistory::minor('12.345', 2), 'invalid_price_precision');
$reject(static fn () => PriceHistory::minor('-1', 2), 'invalid_price');
$equal(Merchandising::campaignState(['state' => 'scheduled', 'approved_by' => '3', 'starts_at' => '2026-01-01T00:00:00Z', 'ends_at' => '2026-02-01T00:00:00Z'], strtotime('2026-02-02T00:00:00Z')), 'ended', 'TEST-U049 delayed job cannot extend campaign');
$equal(Merchandising::campaignState(['state' => 'draft', 'approved_by' => null], time()), 'draft', 'unapproved campaign remains draft');
$equal(LoyaltyPolicy::proportional(50, 100, 100), 50, 'original-rule proportional refund');
$equal(LoyaltyPolicy::proportional(1, 3, 2), 1, 'explicit floor rounding');
$equal(LoyaltyPolicy::proportional(1, 1, 3), 0, 'fractional points do not inflate');
$equal(LoyaltyPolicy::proportional(999999999999999, 1000000000, 999999999999999), 1000000000, 'large money product does not overflow');
$equal(Loyalty::major('1', 2), '0.01', 'reward coupon exact native amount');
$equal(Loyalty::major('1000', 0), '1000', 'zero exponent currency');
$reject(static fn () => LoyaltyPolicy::proportional(999999999999999, 1000000000, 1), 'points_out_of_range');
$reject(static fn () => LoyaltyPolicy::proportional(-1, 1, 1), 'arithmetic_range');
$reject(static fn () => Loyalty::major('1.1', 2), 'invalid_reward_money');
echo "Catalog domain checks passed: {$count}\n";
